/*
 * Target: STM32L476 (TIM6 update → TRGO → DMA → DAC1_CH1)
 *
 * How it works:
 * 1) A small lookup table (100 samples) holds "One" period of the waveform (sine/square)
 * 2) TIM6 generates an "update" event at a fixed sample rate Fs (times per second)
 * 3) Each update triggers the DMA to move the next sample into the DAC register
 * 4) After 100 samples the DMA wraps around to the start (circular), so you get a periodic signal.
 * 		If Fs = 100 * Fout, the DAC outputs Fout Hz.
 *
 * 	User needs to change: waveform type and output frequency. Everything else runs in hardware (timer + DMA + DAC), so the CPU stays free.
*/


